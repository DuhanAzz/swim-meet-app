// Pastikan Login sebagai Admin/Master
if (!isset($_SESSION['role']) || ($_SESSION['role'] !== 'admin' && $_SESSION['role'] !== 'master')) die("Akses Ditolak.");

$event_id = $_GET['event_id'] ?? 0;

// Ambil Data Event
$stmt = $pdo->prepare("SELECT * FROM events WHERE id = ?");
$stmt->execute([$event_id]);
$event = $stmt->fetch();
if (!$event) die("Event tidak ditemukan");

// Ambil Data Seri (Heats) - VERSI PERBAIKAN (Tanpa entry_time)
$stmt = $pdo->prepare("SELECT 
    he.lane_number, 
    s.nama_atlet, 
    c.nama_klub, 
    h.heat_number 
    FROM heat_entries he
    JOIN heats h ON he.heat_id = h.id
    JOIN swimmers s ON he.swimmer_id = s.id
    JOIN clubs c ON s.club_id = c.id
    WHERE h.event_id = ?
    ORDER BY h.heat_number ASC, he.lane_number ASC");
$stmt->execute([$event_id]);
$entries = $stmt->fetchAll(PDO::FETCH_GROUP); // Grouping by Heat Number otomatis

// Re-organize data by Heat
$heats = [];
foreach($entries as $row) {
    $heats[$row['heat_number']][] = $row;
}
